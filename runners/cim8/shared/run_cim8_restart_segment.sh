#!/usr/bin/env bash
set -euo pipefail

START_HOUR="${1:?Informe a hora inicial do restart}"
END_HOUR="${2:?Informe a hora final do restart}"
ROOT="${GITHUB_WORKSPACE:-$PWD}"
RUN_DIR="$ROOT/wrf_work/run"
IMAGE="dtcenter/wps_wrf:latest"
MPI_PROCS="${WRF_MPI_PROCS:-4}"
TIME_STEP="${WRF_TIME_STEP:-30}"
HISTORY_INTERVAL="${WRF_HISTORY_INTERVAL_MINUTES:-60}"

(( START_HOUR > 0 && END_HOUR > START_HOUR && END_HOUR <= 72 )) || {
  echo "Intervalo de restart CIM inválido: F$START_HOUR-F$END_HOUR" >&2
  exit 2
}
(( TIME_STEP > 0 && MPI_PROCS > 0 && HISTORY_INTERVAL > 0 )) || {
  echo "MPI, time_step ou history_interval inválido" >&2
  exit 2
}

test -d "$RUN_DIR" || { echo "Diretório de execução não restaurado: $RUN_DIR" >&2; exit 3; }
test -s "$RUN_DIR/sideral-run.env" || { echo "Arquivo .sideral-run.env ausente no checkpoint CIM" >&2; exit 4; }
# The run-date file is generated by the first segment and is part of the checkpoint TAR.
source "$RUN_DIR/.sideral-run.env"
[[ "${RUN_DATE:-}" =~ ^[0-9]{8}$ ]] || { echo "RUN_DATE inválido no checkpoint: ${RUN_DATE:-}" >&2; exit 5; }
[[ "${RUN_CYCLE:-}" =~ ^(00|06|12|18)$ ]] || { echo "RUN_CYCLE inválido no checkpoint: ${RUN_CYCLE:-}" >&2; exit 5; }

START_ISO="$(date -u -d "$RUN_DATE $RUN_CYCLE:00 UTC +$START_HOUR hours" +%Y-%m-%d_%H:%M:%S)"
END_ISO="$(date -u -d "$RUN_DATE $RUN_CYCLE:00 UTC +$END_HOUR hours" +%Y-%m-%d_%H:%M:%S)"
EXPECTED_RESTART="wrfrst_d01_$START_ISO"

test -s "$RUN_DIR/wrfbdy_d01" || { echo "wrfbdy_d01 ausente no checkpoint CIM" >&2; exit 6; }
test -s "$RUN_DIR/wrfinput_d01" || { echo "wrfinput_d01 ausente no checkpoint CIM" >&2; exit 7; }
test -s "$RUN_DIR/$EXPECTED_RESTART" || {
  echo "Restart esperado não encontrado: $RUN_DIR/$EXPECTED_RESTART" >&2
  find "$RUN_DIR" -maxdepth 1 -type f -name 'wrfrst_d01_*' -printf '%f %s bytes\n' | sort >&2 || true
  exit 8
}

# Keep only the exact restart that matches the requested continuation time.
find "$RUN_DIR" -maxdepth 1 -type f -name 'wrfrst_d01_*' ! -name "$EXPECTED_RESTART" -delete

python3 - "$RUN_DIR/namelist.input" "$RUN_DATE" "$RUN_CYCLE" "$START_HOUR" "$END_HOUR" "$TIME_STEP" "$HISTORY_INTERVAL" <<'PY'
from datetime import datetime, timedelta, timezone
from pathlib import Path
import re
import sys

path = Path(sys.argv[1])
run_date, run_cycle = sys.argv[2], sys.argv[3]
start_hour, end_hour = int(sys.argv[4]), int(sys.argv[5])
time_step, history_interval = int(sys.argv[6]), int(sys.argv[7])
base = datetime.strptime(run_date + run_cycle, "%Y%m%d%H").replace(tzinfo=timezone.utc)
start = base + timedelta(hours=start_hour)
end = base + timedelta(hours=end_hour)
text = path.read_text(encoding="utf-8")

values = {
    "run_days": 0,
    "run_hours": end_hour - start_hour,
    "run_minutes": 0,
    "run_seconds": 0,
    "start_year": start.year,
    "start_month": start.month,
    "start_day": start.day,
    "start_hour": start.hour,
    "end_year": end.year,
    "end_month": end.month,
    "end_day": end.day,
    "end_hour": end.hour,
    "restart_interval": (end_hour - start_hour) * 60,
    "history_interval": history_interval,
    "time_step": time_step,
}
for key, value in values.items():
    pattern = rf"(?m)^(\s*{re.escape(key)}\s*=\s*)[^,\n]+(,\s*)$"
    text, count = re.subn(pattern, rf"\g<1>{value}\g<2>", text, count=1)
    if count != 1:
        raise SystemExit(f"Campo {key} ausente ou duplicado na namelist.input")

for key, value in (
    ("restart", ".true."),
    ("override_restart_timers", ".true."),
):
    pattern = rf"(?m)^(\s*{re.escape(key)}\s*=\s*)[^,\n]+(,\s*)$"
    text, count = re.subn(pattern, rf"\g<1>{value}\g<2>", text, count=1)
    if count != 1:
        text = text.replace("&time_control", f"&time_control\n {key} = {value},", 1)

path.write_text(text, encoding="utf-8")
print(f"CIM WRF restart: {start.isoformat()} -> {end.isoformat()}; {end_hour-start_hour} h; dt={time_step} s")
PY

echo "CIM 8 km: continuando F$START_HOUR-F$END_HOUR usando $EXPECTED_RESTART"
docker run --rm \
  --entrypoint /bin/bash \
  -e OMPI_ALLOW_RUN_AS_ROOT=1 \
  -e OMPI_ALLOW_RUN_AS_ROOT_CONFIRM=1 \
  -e WRF_MPI_PROCS="$MPI_PROCS" \
  -v "$RUN_DIR:/work/run" \
  "$IMAGE" -lc '
    set -euo pipefail
    cd /work/run
    test -s wrfbdy_d01
    test -s "$1"
    echo "=== WRF CIM 8 KM RESTART ==="
    mpirun --allow-run-as-root --oversubscribe --bind-to none -np "$WRF_MPI_PROCS" \
      /comsoftware/wrf/WRF-4.3/main/wrf.exe > rsl.out.cim-restart 2>&1 || {
        STATUS=$?
        tail -260 rsl.error.0000 2>/dev/null || true
        tail -260 rsl.out.cim-restart 2>/dev/null || true
        exit "$STATUS"
      }
    grep -q "SUCCESS COMPLETE WRF" rsl.error.0000 || {
      echo "WRF restart CIM não confirmou SUCCESS COMPLETE WRF" >&2
      tail -260 rsl.error.0000 2>/dev/null || true
      tail -260 rsl.out.cim-restart 2>/dev/null || true
      exit 51
    }
  ' -- "$EXPECTED_RESTART"

shopt -s nullglob
WRFOUTS=("$RUN_DIR"/wrfout_d01_*)
shopt -u nullglob
(("${#WRFOUTS[@]}" > 0)) || { echo "Nenhum wrfout CIM após restart" >&2; exit 52; }
echo "Restart CIM concluído. wrfout disponíveis: ${#WRFOUTS[@]}"
